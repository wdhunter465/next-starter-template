#!/usr/bin/env node
/**
 * lgfc-ci-storm-issue-triage.mjs
 *
 * LGFC-owned issue triage utility for identifying CI alert-storm noise.
 *
 * This script is intentionally conservative. It is not a general backlog cleanup
 * tool. It exists to classify open LGFC GitHub issues into review buckets and,
 * only after human review, close reviewed CI storm-noise candidates with an
 * audit comment.
 *
 * Repository target:
 *   wdhunter465/next-starter-template
 *
 * Modes:
 *   report
 *     Fetch open issues and generate:
 *       - ops-artifacts/issue-triage/lgfc-open-issue-triage-report.md
 *       - ops-artifacts/issue-triage/lgfc-ci-storm-clusters.md
 *       - ops-artifacts/issue-triage/lgfc-ci-storm-candidates.json
 *
 *   close-reviewed-storm
 *     Close only issues listed in a reviewed candidate JSON file generated by
 *     report mode. This mode refuses to act unless all safety controls pass.
 *
 *   self-test
 *     Offline classification + confirmation fail-closed checks (no gh, no closes).
 *
 * Required safety controls:
 *   - Storm classification requires --incident-start and --incident-end.
 *   - Close mode requires --candidate-file, --root-issue, and exact confirmation:
 *       --confirm-close-reviewed=LGFC-CLOSE-CI-STORM-NOISE
 *   - Close mode re-fetches every candidate issue and verifies number, title,
 *     createdAt, URL, state, and bucket before closure.
 *   - PMO_PROCESS and NEEDS_REVIEW buckets are never eligible for closure.
 *   - Every closed issue receives an audit comment referencing the root issue.
 *
 * Requirements:
 *   - gh CLI authenticated with issue read/write access
 *   - Node 18+
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const DEFAULT_LGFC_REPO = 'wdhunter465/next-starter-template';
let LGFC_REPO = DEFAULT_LGFC_REPO;
const OUTPUT_DIR = 'ops-artifacts/issue-triage';
const TRIAGE_REPORT_PATH = join(OUTPUT_DIR, 'lgfc-open-issue-triage-report.md');
const CLUSTER_REPORT_PATH = join(OUTPUT_DIR, 'lgfc-ci-storm-clusters.md');
const CANDIDATE_JSON_PATH = join(OUTPUT_DIR, 'lgfc-ci-storm-candidates.json');

const STORM_WINDOW_MINUTES = 20;
const STORM_MIN_CLUSTER_SIZE = 3;
const PMO_TITLE_PATTERN = /^(PROGRAM CANDIDATE|OPS GAP|GAP PLAN):/i;
const PMO_LABEL_NAME = 'change-ops';
const CLOSE_CONFIRMATION = 'LGFC-CLOSE-CI-STORM-NOISE';
const ALLOWED_REPOS = new Set([DEFAULT_LGFC_REPO]);

const args = process.argv.slice(2);

function resolveRepo() {
  const requested = getArg('repo', DEFAULT_LGFC_REPO);
  if (!ALLOWED_REPOS.has(requested)) {
    fail(
      `Refusing repo '${requested}'. Only ${DEFAULT_LGFC_REPO} is allowed (live LGFC owner). ` +
        'Historical wdhunter645 draft slug is rejected (#3215 identity drift).',
    );
  }
  LGFC_REPO = requested;
  return LGFC_REPO;
}

function getArg(name, fallback = null) {
  const prefix = `--${name}=`;
  const hit = args.find((arg) => arg.startsWith(prefix));
  if (hit) return hit.slice(prefix.length);
  return args.includes(`--${name}`) ? true : fallback;
}

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

function runGh(ghArgs, options = {}) {
  try {
    return execFileSync('gh', ghArgs, {
      encoding: 'utf8',
      maxBuffer: 1024 * 1024 * 64,
      ...options,
    });
  } catch (error) {
    fail(`gh command failed: gh ${ghArgs.join(' ')}\n${error.message}`);
  }
}

function parseIsoDateRequired(value, name) {
  if (!value) fail(`Missing --${name}=<ISO timestamp>`);
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) fail(`Invalid --${name}: ${value}`);
  return date;
}

function ensureOutputDir() {
  if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true });
}

function assertGhAuth() {
  runGh(['auth', 'status'], { stdio: 'pipe' });
}

function fetchOpenIssues() {
  const raw = runGh([
    'issue',
    'list',
    '--repo',
    LGFC_REPO,
    '--state',
    'open',
    '--limit',
    '1000',
    '--json',
    'number,title,labels,createdAt,author,url,state',
  ]);
  return JSON.parse(raw);
}

function fetchIssue(number) {
  const raw = runGh([
    'issue',
    'view',
    String(number),
    '--repo',
    LGFC_REPO,
    '--json',
    'number,title,labels,createdAt,author,url,state',
  ]);
  return JSON.parse(raw);
}

function normalizeTitleForClustering(title) {
  return title
    .toLowerCase()
    .replace(/#\d+/g, '#N')
    .replace(/\b\d{4}-\d{2}-\d{2}\b/g, 'DATE')
    .replace(/\b\d+\b/g, 'N')
    .replace(/\s+/g, ' ')
    .trim();
}

function isWithinIncidentWindow(issue, incidentStart, incidentEnd) {
  const createdAt = new Date(issue.createdAt);
  return createdAt >= incidentStart && createdAt <= incidentEnd;
}

function isPmoProcessIssue(issue) {
  const hasPmoLabel = issue.labels?.some((label) => label.name === PMO_LABEL_NAME);
  const hasPmoTitle = PMO_TITLE_PATTERN.test(issue.title);
  return Boolean(hasPmoLabel && hasPmoTitle);
}

function findStormClusters(issues, incidentStart, incidentEnd) {
  const incidentIssues = issues.filter((issue) =>
    isWithinIncidentWindow(issue, incidentStart, incidentEnd)
  );

  const byNormalizedTitle = new Map();
  for (const issue of incidentIssues) {
    const key = normalizeTitleForClustering(issue.title);
    if (!byNormalizedTitle.has(key)) byNormalizedTitle.set(key, []);
    byNormalizedTitle.get(key).push(issue);
  }

  const clusters = [];
  for (const [normalizedTitle, group] of byNormalizedTitle.entries()) {
    const sorted = [...group].sort(
      (a, b) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime()
    );

    let current = [];
    for (const issue of sorted) {
      if (current.length === 0) {
        current = [issue];
        continue;
      }

      const previousCreatedAt = new Date(current[current.length - 1].createdAt);
      const currentCreatedAt = new Date(issue.createdAt);
      const diffMinutes = (currentCreatedAt.getTime() - previousCreatedAt.getTime()) / 60000;

      if (diffMinutes <= STORM_WINDOW_MINUTES) {
        current.push(issue);
      } else {
        if (current.length >= STORM_MIN_CLUSTER_SIZE) {
          clusters.push({ normalizedTitle, issues: current });
        }
        current = [issue];
      }
    }

    if (current.length >= STORM_MIN_CLUSTER_SIZE) {
      clusters.push({ normalizedTitle, issues: current });
    }
  }

  return clusters;
}

function classifyIssues(issues, incidentStart, incidentEnd) {
  const stormClusters = findStormClusters(issues, incidentStart, incidentEnd);
  const stormIssueNumbers = new Set(
    stormClusters.flatMap((cluster) => cluster.issues.map((issue) => issue.number))
  );

  const buckets = {
    PMO_PROCESS: [],
    STORM_NOISE_CANDIDATE: [],
    NEEDS_REVIEW: [],
  };

  for (const issue of issues) {
    if (stormIssueNumbers.has(issue.number)) {
      buckets.STORM_NOISE_CANDIDATE.push(issue);
    } else if (isPmoProcessIssue(issue)) {
      buckets.PMO_PROCESS.push(issue);
    } else {
      buckets.NEEDS_REVIEW.push(issue);
    }
  }

  return { buckets, stormClusters };
}

function issueLine(issue) {
  return `- #${issue.number} — ${issue.title} (opened ${issue.createdAt}) ${issue.url}`;
}

function writeTriageReport({ buckets, incidentStart, incidentEnd }) {
  const total =
    buckets.PMO_PROCESS.length +
    buckets.STORM_NOISE_CANDIDATE.length +
    buckets.NEEDS_REVIEW.length;

  const lines = [];
  lines.push('# LGFC Open Issue Triage Report');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push(`Repo: ${LGFC_REPO}`);
  lines.push(`Incident window: ${incidentStart.toISOString()} through ${incidentEnd.toISOString()}`);
  lines.push(`Storm window minutes: ${STORM_WINDOW_MINUTES}`);
  lines.push(`Storm minimum cluster size: ${STORM_MIN_CLUSTER_SIZE}`);
  lines.push('');
  lines.push(`Total open issues classified: ${total}`);
  lines.push('');

  lines.push(`## PMO_PROCESS (${buckets.PMO_PROCESS.length})`);
  lines.push('Deliberate PMO/gap/program artifacts. Never eligible for automated closure.');
  lines.push('');
  buckets.PMO_PROCESS.forEach((issue) => lines.push(issueLine(issue)));
  lines.push('');

  lines.push(`## STORM_NOISE_CANDIDATE (${buckets.STORM_NOISE_CANDIDATE.length})`);
  lines.push('Candidate CI storm-noise issues. Review manually before any closure run.');
  lines.push('');
  buckets.STORM_NOISE_CANDIDATE.forEach((issue) => lines.push(issueLine(issue)));
  lines.push('');

  lines.push(`## NEEDS_REVIEW (${buckets.NEEDS_REVIEW.length})`);
  lines.push('Default legitimate-work bucket. Never eligible for automated closure.');
  lines.push('');
  buckets.NEEDS_REVIEW.forEach((issue) => lines.push(issueLine(issue)));
  lines.push('');

  writeFileSync(TRIAGE_REPORT_PATH, lines.join('\n'), 'utf8');
}

function writeClusterReport({ stormClusters, incidentStart, incidentEnd }) {
  const lines = [];
  lines.push('# LGFC CI Storm Cluster Detail');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push(`Repo: ${LGFC_REPO}`);
  lines.push(`Incident window: ${incidentStart.toISOString()} through ${incidentEnd.toISOString()}`);
  lines.push(`Detected clusters: ${stormClusters.length}`);
  lines.push('');

  stormClusters.forEach((cluster, index) => {
    const first = cluster.issues[0].createdAt;
    const last = cluster.issues[cluster.issues.length - 1].createdAt;
    lines.push(`## Cluster ${index + 1} — ${cluster.issues.length} issues`);
    lines.push(`Normalized title: \`${cluster.normalizedTitle}\``);
    lines.push(`Span: ${first} through ${last}`);
    lines.push('');
    cluster.issues.forEach((issue) => lines.push(issueLine(issue)));
    lines.push('');
  });

  writeFileSync(CLUSTER_REPORT_PATH, lines.join('\n'), 'utf8');
}

function writeCandidateJson({ buckets, stormClusters, incidentStart, incidentEnd }) {
  const candidates = buckets.STORM_NOISE_CANDIDATE.map((issue) => ({
    number: issue.number,
    title: issue.title,
    createdAt: issue.createdAt,
    url: issue.url,
    bucket: 'STORM_NOISE_CANDIDATE',
  }));

  const payload = {
    schema: 'lgfc-ci-storm-candidates/v1',
    generatedAt: new Date().toISOString(),
    repo: LGFC_REPO,
    incidentStart: incidentStart.toISOString(),
    incidentEnd: incidentEnd.toISOString(),
    stormWindowMinutes: STORM_WINDOW_MINUTES,
    stormMinClusterSize: STORM_MIN_CLUSTER_SIZE,
    candidateCount: candidates.length,
    clusterCount: stormClusters.length,
    candidates,
  };

  writeFileSync(CANDIDATE_JSON_PATH, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
}

function runReportMode() {
  const incidentStart = parseIsoDateRequired(getArg('incident-start'), 'incident-start');
  const incidentEnd = parseIsoDateRequired(getArg('incident-end'), 'incident-end');
  if (incidentStart >= incidentEnd) fail('--incident-start must be before --incident-end');

  assertGhAuth();
  ensureOutputDir();

  const issues = fetchOpenIssues();
  const { buckets, stormClusters } = classifyIssues(issues, incidentStart, incidentEnd);

  writeTriageReport({ buckets, incidentStart, incidentEnd });
  writeClusterReport({ stormClusters, incidentStart, incidentEnd });
  writeCandidateJson({ buckets, stormClusters, incidentStart, incidentEnd });

  console.log('LGFC issue triage report complete. No issues were modified.');
  console.log(`PMO_PROCESS: ${buckets.PMO_PROCESS.length}`);
  console.log(`STORM_NOISE_CANDIDATE: ${buckets.STORM_NOISE_CANDIDATE.length}`);
  console.log(`NEEDS_REVIEW: ${buckets.NEEDS_REVIEW.length}`);
  console.log(`Wrote: ${TRIAGE_REPORT_PATH}`);
  console.log(`Wrote: ${CLUSTER_REPORT_PATH}`);
  console.log(`Wrote: ${CANDIDATE_JSON_PATH}`);
}

function loadCandidateFile(path) {
  if (!path) fail('Missing --candidate-file=<path>');
  if (!existsSync(path)) fail(`Candidate file does not exist: ${path}`);

  const payload = JSON.parse(readFileSync(path, 'utf8'));
  if (payload.schema !== 'lgfc-ci-storm-candidates/v1') {
    fail(`Unexpected candidate file schema: ${payload.schema}`);
  }
  if (payload.repo !== LGFC_REPO) {
    fail(`Candidate file repo mismatch: ${payload.repo}`);
  }
  if (!Array.isArray(payload.candidates)) {
    fail('Candidate file is missing candidates array');
  }
  return payload;
}

function assertRootIssue(rootIssueNumber) {
  if (!rootIssueNumber) fail('Missing --root-issue=<number>');
  const rootIssue = fetchIssue(rootIssueNumber);
  if (rootIssue.state !== 'OPEN') {
    fail(`Root issue #${rootIssueNumber} must be open before closure run; current state: ${rootIssue.state}`);
  }
}

function assertCandidateStillMatches(candidate, liveIssue) {
  if (candidate.bucket !== 'STORM_NOISE_CANDIDATE') {
    fail(`#${candidate.number} is not a storm-noise candidate in reviewed file`);
  }
  if (liveIssue.state !== 'OPEN') {
    fail(`#${candidate.number} is not open; current state: ${liveIssue.state}`);
  }
  if (liveIssue.title !== candidate.title) {
    fail(`#${candidate.number} title changed since report generation`);
  }
  if (liveIssue.createdAt !== candidate.createdAt) {
    fail(`#${candidate.number} createdAt changed since report generation`);
  }
  if (liveIssue.url !== candidate.url) {
    fail(`#${candidate.number} URL changed since report generation`);
  }
}

function closeIssue(candidate, rootIssueNumber) {
  const comment = [
    `Closed as reviewed LGFC CI alert-storm noise.`,
    ``,
    `Root tracking issue: #${rootIssueNumber}`,
    `Reviewed candidate source: ${candidate.url}`,
    ``,
    `This closure does not classify the underlying CI defect as resolved. It only removes a duplicate/looping alert artifact from the open issue backlog. If this issue represents a distinct live defect, reopen it with evidence explaining the distinct cause.`,
  ].join('\n');

  runGh([
    'issue',
    'close',
    String(candidate.number),
    '--repo',
    LGFC_REPO,
    '--comment',
    comment,
  ], { stdio: 'inherit' });
}

function runCloseReviewedStormMode() {
  const candidateFile = getArg('candidate-file');
  const rootIssueNumber = getArg('root-issue');
  const confirmation = getArg('confirm-close-reviewed');

  if (confirmation !== CLOSE_CONFIRMATION) {
    fail(`Refusing close mode. Required: --confirm-close-reviewed=${CLOSE_CONFIRMATION}`);
  }

  assertGhAuth();
  assertRootIssue(rootIssueNumber);

  const payload = loadCandidateFile(candidateFile);
  if (payload.candidates.length === 0) {
    console.log('Candidate file has zero storm-noise candidates. Nothing to close.');
    return;
  }

  console.log(`Preparing to close ${payload.candidates.length} reviewed storm-noise candidate(s).`);

  for (const candidate of payload.candidates) {
    const liveIssue = fetchIssue(candidate.number);
    assertCandidateStillMatches(candidate, liveIssue);
  }

  for (const candidate of payload.candidates) {
    closeIssue(candidate, rootIssueNumber);
  }

  console.log(`Closed ${payload.candidates.length} reviewed storm-noise candidate(s).`);
}


function runSelfTestMode() {
  // Offline safety/unit checks — never calls gh and never closes issues.
  const start = new Date('2026-06-25T00:00:00Z');
  const end = new Date('2026-06-25T01:00:00Z');
  const fixture = [
    {
      number: 1,
      title: 'Production Audit Failed (Playwright Invariants)',
      createdAt: '2026-06-25T00:05:00Z',
      labels: [],
      url: 'https://example.test/1',
      state: 'OPEN',
    },
    {
      number: 2,
      title: 'Production Audit Failed (Playwright Invariants)',
      createdAt: '2026-06-25T00:10:00Z',
      labels: [],
      url: 'https://example.test/2',
      state: 'OPEN',
    },
    {
      number: 3,
      title: 'Production Audit Failed (Playwright Invariants)',
      createdAt: '2026-06-25T00:15:00Z',
      labels: [],
      url: 'https://example.test/3',
      state: 'OPEN',
    },
    {
      number: 4,
      title: 'OPS GAP: Controlled CI storm issue triage utility',
      createdAt: '2026-06-25T00:20:00Z',
      labels: [{ name: 'change-ops' }],
      url: 'https://example.test/4',
      state: 'OPEN',
    },
  ];

  const { buckets, stormClusters } = classifyIssues(fixture, start, end);
  if (stormClusters.length !== 1) fail(`self-test expected 1 cluster, got ${stormClusters.length}`);
  if (buckets.STORM_NOISE_CANDIDATE.length !== 3) {
    fail(`self-test expected 3 storm candidates, got ${buckets.STORM_NOISE_CANDIDATE.length}`);
  }
  if (buckets.PMO_PROCESS.length !== 1) fail(`self-test expected 1 PMO issue, got ${buckets.PMO_PROCESS.length}`);
  if (buckets.NEEDS_REVIEW.length !== 0) fail(`self-test expected 0 needs-review, got ${buckets.NEEDS_REVIEW.length}`);

  // Close confirmation must refuse wrong phrase without side effects.
  const previousArgv = [...args];
  args.length = 0;
  args.push('--mode=close-reviewed-storm', '--confirm-close-reviewed=WRONG');
  let refused = false;
  const previousExit = process.exit;
  process.exit = (code) => {
    refused = code === 1;
    throw new Error('exit');
  };
  const previousError = console.error;
  console.error = () => {};
  try {
    runCloseReviewedStormMode();
  } catch (error) {
    if (error.message !== 'exit') throw error;
  } finally {
    process.exit = previousExit;
    console.error = previousError;
    args.length = 0;
    args.push(...previousArgv);
  }
  if (!refused) fail('self-test expected close mode to refuse wrong confirmation');

  console.log('self-test PASS');
}

function main() {
  const mode = getArg('mode', 'report');

  if (mode === 'self-test') {
    runSelfTestMode();
    return;
  }

  if (mode === 'report') {
    resolveRepo();
    runReportMode();
    return;
  }

  if (mode === 'close-reviewed-storm') {
    resolveRepo();
    runCloseReviewedStormMode();
    return;
  }

  fail(`Unsupported --mode=${mode}. Use report, close-reviewed-storm, or self-test.`);
}

main();
